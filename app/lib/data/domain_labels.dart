/// « lexicography, education » -> « lexicographie, éducation ».
String domainFr(String domain) {
  return domain.split(',').map((part) {
    final key = part.trim().toLowerCase().replaceAll(RegExp(r'[_-]+'), ' ');
    return _domainFr[key] ?? part.trim();
  }).join(', ');
}
